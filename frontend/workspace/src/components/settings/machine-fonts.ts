export async function readLocalFonts() {
  const host = window as Window & { queryLocalFonts?: () => Promise<Array<{ family: string }>> }
  if (!host.queryLocalFonts) return []
  try {
    const faces = await host.queryLocalFonts()
    const names = [...new Set(faces.map((face) => face.family).filter((name) => name.length > 0))]
    names.sort((a, b) => a.localeCompare(b))
    return names
  } catch {
    return []
  }
}
